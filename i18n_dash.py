LANGS = [("🇰🇷 한국어", "ko"), ("🇯🇵 日本語", "ja")]


def T(text, lang="ko"):
    """한국어 원문 → 선택 언어. 사전에 없으면 원문 그대로."""
    if lang != "ja":
        return text
    return JA.get(text, text)


def lang_selector(st, key="dash_lang"):
    """사이드바에 언어 선택을 그리고 현재 언어 코드('ko'/'ja')를 반환.

    URL 쿼리 ?lang=ja 로 들어오면 그 값을 초기값으로 쓴다.
    스크리너 일본어판 → 마켓 지표 링크에 ?lang=ja 를 붙이면 이어서 일본어로 열린다.
    """
    default = "ko"
    try:
        q = st.query_params.get("lang")
        if q in ("ko", "ja"):
            default = q
    except Exception:
        pass
    if key not in st.session_state:
        st.session_state[key] = default

    labels = [a for a, _ in LANGS]
    codes = [b for _, b in LANGS]
    idx = codes.index(st.session_state[key]) if st.session_state[key] in codes else 0
    picked = st.radio("🌐 Language", labels, index=idx, horizontal=True,
                      key=key + "_radio", label_visibility="collapsed")
    lang = codes[labels.index(picked)]
    st.session_state[key] = lang
    return lang


